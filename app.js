function getTier(accuracy) {
  if (accuracy >= 85) return { label: "AI Whisperer",            emoji: "🔮" };
  if (accuracy >= 70) return { label: "Suspiciously Perceptive", emoji: "🕵️" };
  if (accuracy >= 55) return { label: "Getting Suspicious",      emoji: "🤔" };
  if (accuracy >= 40) return { label: "Coin Flip Energy",        emoji: "🪙" };
  return                     { label: "Easily Fooled",           emoji: "🤖" };
}

function computeScore() {
  const votes   = state.votes;
  const correct = votes.filter(v => v.correct).length;
  const accuracy = (correct / votes.length) * 100;
  const tier    = getTier(accuracy);

  const byType = {};
  for (const t of ["tweet", "linkedin", "blog"]) {
    const tv = votes.filter(v => v.type === t);
    const tc = tv.filter(v => v.correct).length;
    byType[t] = {
      total:    tv.length,
      correct:  tc,
      accuracy: tv.length > 0 ? (tc / tv.length) * 100 : null,
    };
  }

  const wrong = votes.filter(v => !v.correct);
  const missedAI  = wrong.filter(v => v.isAI);   // AI but guessed Human
  const falseAI   = wrong.filter(v => !v.isAI);  // Human but guessed AI
  const errors = {
    total:       wrong.length,
    missedAI:    missedAI.length,
    falseAI:     falseAI.length,
    missedAIPct: wrong.length > 0 ? Math.round((missedAI.length / wrong.length) * 100) : 0,
    falseAIPct:  wrong.length > 0 ? Math.round((falseAI.length  / wrong.length) * 100) : 0,
  };

  return { total: votes.length, correct, accuracy, byType, tier, errors };
}

